CREATE TABLE secciones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(255) NOT NULL, slug VARCHAR(40) NOT NULL UNIQUE,
 descripcion VARCHAR(255), activa BOOLEAN NOT NULL
);
CREATE TABLE productos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(255) NOT NULL, descripcion VARCHAR(255), precio NUMERIC(6,2) NOT NULL CHECK (precio > 0),
 seccion_id BIGINT NOT NULL REFERENCES secciones(id), disponible BOOLEAN NOT NULL,
 imagen_url VARCHAR(300), etiqueta VARCHAR(255)
);
CREATE INDEX idx_producto_seccion ON productos(seccion_id);
CREATE TABLE mesas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero INTEGER NOT NULL UNIQUE, capacidad INTEGER NOT NULL CHECK (capacidad BETWEEN 1 AND 20),
 tipo VARCHAR(255) NOT NULL, zona VARCHAR(255) NOT NULL, estado VARCHAR(255) NOT NULL
);
CREATE TABLE cuentas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE,
 clave_hash VARCHAR(255) NOT NULL, rol VARCHAR(30) NOT NULL,
 activa BOOLEAN NOT NULL
);
