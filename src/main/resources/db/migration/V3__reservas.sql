-- Reservas de mesa hechas por clientes. Una reserva ocupa la mesa desde hora_inicio hasta hora_fin.
-- El cruce de horarios en la misma mesa se impide en ReservaServicio bloqueando la fila de la mesa.
CREATE TABLE reservas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cuenta_id BIGINT NOT NULL REFERENCES cuentas(id),
 mesa_id BIGINT NOT NULL REFERENCES mesas(id),
 fecha DATE NOT NULL,
 hora_inicio TIME NOT NULL,
 hora_fin TIME NOT NULL,
 personas INTEGER NOT NULL,
 estado VARCHAR(20) NOT NULL,
 nota VARCHAR(200),
 creado_en TIMESTAMP NOT NULL,
 CONSTRAINT ck_reservas_personas CHECK (personas BETWEEN 1 AND 20),
 CONSTRAINT ck_reservas_horas CHECK (hora_fin > hora_inicio),
 CONSTRAINT ck_reservas_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA', 'NO_ASISTIO'))
);
CREATE INDEX idx_reservas_fecha ON reservas(fecha);
CREATE INDEX idx_reservas_mesa_fecha ON reservas(mesa_id, fecha);
CREATE INDEX idx_reservas_cuenta ON reservas(cuenta_id);
